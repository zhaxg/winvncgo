func desKey(key []byte, edf int) {
	var pc1m [56]byte
	var pcr [56]byte
	var kn [32]uint32

	for j := 0; j < 56; j++ {
		l := int(pc1[j])
		m := l & 7
		if key[l>>3]&byte(bytebit[m]) != 0 {
			pc1m[j] = 1
		}
	}

	for i := 0; i < 16; i++ {
		var m, n int
		if edf == 1 { // DE1
			m = (15 - i) << 1
		} else {
			m = i << 1
		}
		n = m + 1
		kn[m] = 0
		kn[n] = 0

		for j := 0; j < 28; j++ {
			l := j + int(totrot[i])
			if l < 28 {
				pcr[j] = pc1m[l]
			} else {
				pcr[j] = pc1m[l-28]
			}
		}
		for j := 28; j < 56; j++ {
			l := j + int(totrot[i])
			if l < 56 {
				pcr[j] = pc1m[l]
			} else {
				pcr[j] = pc1m[l-28]
			}
		}
		for j := 0; j < 24; j++ {
			if pcr[pc2[j]] != 0 {
				kn[m] |= bigbyte[j]
			}
			if pcr[pc2[j+24]] != 0 {
				kn[n] |= bigbyte[j]
			}
		}
	}

	// cookey
	var dough [32]uint32
	cook := 0
	raw1 := 0
	for i := 0; i < 16; i++ {
		raw0 := raw1
		raw1++
		dough[cook] = (kn[raw0] & 0x00fc0000) << 6
		dough[cook] |= (kn[raw0] & 0x00000fc0) << 10
		dough[cook] |= (kn[raw1] & 0x00fc0000) >> 10
		dough[cook] |= (kn[raw1] & 0x00000fc0) >> 6
		cook++
		dough[cook] = (kn[raw0] & 0x0003f000) << 12
		dough[cook] |= (kn[raw0] & 0x0000003f) << 16
		dough[cook] |= (kn[raw1] & 0x0003f000) >> 4
		dough[cook] |= (kn[raw1] & 0x0000003f)
		cook++
		raw1++
	}

	copy(knL[:], dough[:])
}

func desBlock(inblock, outblock []byte) {
	var work [2]uint32

	// scrunch
	work[0] = uint32(inblock[0])<<24 | uint32(inblock[1])<<16 | uint32(inblock[2])<<8 | uint32(inblock[3])
	work[1] = uint32(inblock[4])<<24 | uint32(inblock[5])<<16 | uint32(inblock[6])<<8 | uint32(inblock[7])

	// desfunc
	leftt := work[0]
	right := work[1]
	var round int
	var fval, fwork uint32

	fwork = ((leftt >> 4) ^ right) & 0x0f0f0f0f
	right ^= fwork
	leftt ^= fwork << 4
	fwork = ((leftt >> 16) ^ right) & 0x0000ffff
	right ^= fwork
	leftt ^= fwork << 16
	fwork = ((right >> 2) ^ leftt) & 0x33333333
	leftt ^= fwork
	right ^= fwork << 2
	fwork = ((right >> 8) ^ leftt) & 0x00ff00ff
	leftt ^= fwork
	right ^= fwork << 8
	right = (right << 1) | ((right >> 31) & 1)
	fwork = (leftt ^ right) & 0xaaaaaaaa
	leftt ^= fwork
	right ^= fwork
	leftt = (leftt << 1) | ((leftt >> 31) & 1)

	for round = 0; round < 8; round++ {
		fwork = (right << 28) | (right >> 4)
		fwork ^= knL[round*4]
		fval = sp7[fwork&0x3f]
		fval |= sp5[(fwork>>8)&0x3f]
		fval |= sp3[(fwork>>16)&0x3f]
		fval |= sp1[(fwork>>24)&0x3f]
		fwork = right ^ knL[round*4+1]
		fval |= sp8[fwork&0x3f]
		fval |= sp6[(fwork>>8)&0x3f]
		fval |= sp4[(fwork>>16)&0x3f]
		fval |= sp2[(fwork>>24)&0x3f]
		leftt ^= fval
		fwork = (leftt << 28) | (leftt >> 4)
		fwork ^= knL[round*4+2]
		fval = sp7[fwork&0x3f]
		fval |= sp5[(fwork>>8)&0x3f]
		fval |= sp3[(fwork>>16)&0x3f]
		fval |= sp1[(fwork>>24)&0x3f]
		fwork = leftt ^ knL[round*4+3]
		fval |= sp8[fwork&0x3f]
		fval |= sp6[(fwork>>8)&0x3f]
		fval |= sp4[(fwork>>16)&0x3f]
		fval |= sp2[(fwork>>24)&0x3f]
		right ^= fval
	}

	// inverse permutation
	right = (right << 31) | (right >> 1)
	fwork = (leftt ^ right) & 0xaaaaaaaa
	leftt ^= fwork
	right ^= fwork
	leftt = (leftt << 31) | (leftt >> 1)
	fwork = ((leftt >> 8) ^ right) & 0x00ff00ff
	right ^= fwork
	leftt ^= fwork << 8
	fwork = ((leftt >> 2) ^ right) & 0x33333333
	right ^= fwork
	leftt ^= fwork << 2
	fwork = ((right >> 16) ^ leftt) & 0x0000ffff
	leftt ^= fwork
	right ^= fwork << 16
	fwork = ((right >> 4) ^ leftt) & 0x0f0f0f0f
	leftt ^= fwork
	right ^= fwork << 4

	work[0] = right
	work[1] = leftt

	// unscrun
	outblock[0] = byte((work[0] >> 24) & 0xff)
	outblock[1] = byte((work[0] >> 16) & 0xff)
	outblock[2] = byte((work[0] >> 8) & 0xff)
	outblock[3] = byte(work[0] & 0xff)
	outblock[4] = byte((work[1] >> 24) & 0xff)
	outblock[5] = byte((work[1] >> 16) & 0xff)
	outblock[6] = byte((work[1] >> 8) & 0xff)
	outblock[7] = byte(work[1] & 0xff)
}

// vncEncryptPassword 使用 VNC 标准 DES 加密密码
// 固定密钥来自 d3des: {23,82,107,6,35,78,88,7}
// 输出格式与官方一致：8 字节密文 hex(16 位) + 校验和 hex(2 位)，
// 即 setpasswd.exe 加密后经 WritePrivateProfileStruct 写入 ini 的存储格式
// （参考 libs/setpasswd/setpasswd.cpp 与 inifile.cpp）
func vncEncryptPassword(password string) string {
	// 填充到8字节
	pwd := make([]byte, 8)
	copy(pwd, []byte(password))

	// VNC 固定 DES 密钥，EN0=加密
	key := []byte{23, 82, 107, 6, 35, 78, 88, 7}
	desKey(key, 0) // EN0 = encrypt
	desBlock(pwd, pwd)

	result := ""
	sum := 0
	for _, b := range pwd {
		result += fmt.Sprintf("%02X", b)
		sum += int(b)
	}
	// WritePrivateProfileStruct 在数据后追加 1 字节校验和（各字节之和的低 8 位）
	return result + fmt.Sprintf("%02X", sum%256)
}

// vncDecryptHex 解密 VNC hex 格式的密码，返回明文
// 对应 vncpwd.c 的 vncpwd() 函数（解密模式），兼容 16 位纯密文与 18 位含校验和格式
func vncDecryptHex(hexPwd string) string {
	hexPwd = strings.TrimSpace(hexPwd)
	// hex 解码：8 字节密文，若含末尾校验和（+2 位）则忽略
	n := len(hexPwd) / 2
	if n > 8 {
		n = 8
	}
	pwd := make([]byte, 8) // 始终按8字节块处理
	for i := 0; i < n && i < 8; i++ {
		var b byte
		fmt.Sscanf(hexPwd[i*2:i*2+2], "%02x", &b)
		pwd[i] = b
	}

	// VNC 固定 DES 密钥，DE1=解密
	key := []byte{23, 82, 107, 6, 35, 78, 88, 7}
	desKey(key, 1)
	desBlock(pwd, pwd)

	// 去掉尾部 \x00
	for len(pwd) > 0 && pwd[len(pwd)-1] == 0 {
		pwd = pwd[:len(pwd)-1]
	}
	return string(pwd)
}
